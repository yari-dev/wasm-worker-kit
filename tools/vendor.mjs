#!/usr/bin/env node
/**
 * Copies the kit into a host plugin, under the host plugin's own PHP namespace and text domain.
 *
 *     node tools/vendor.mjs --to ../my-plugin/lib/wasm-worker --namespace "MyPlugin\Worker" --text-domain my-plugin
 *
 * Two plugins bundling different kit versions then never share a class name, and the kit's messages are
 * translated with the plugin (default text domain: `wasm-worker`). Run it again to update.
 */
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

const root = path.resolve( path.dirname( fileURLToPath( import.meta.url ) ), '..' );
const { values: args } = parseArgs( {
	options: {
		to: { type: 'string' },
		namespace: { type: 'string' },
		'text-domain': { type: 'string', default: 'wasm-worker' },
	},
} );

const target = args.to && path.resolve( args.to );
const namespace = ( args.namespace || '' ).replace( /^\\+|\\+$/g, '' );
const domain = args[ 'text-domain' ];

if ( ! target || ! /^[A-Za-z_][A-Za-z0-9_]*(\\[A-Za-z_][A-Za-z0-9_]*)*$/.test( namespace ) || 'WasmWorker' === namespace ) {
	console.error( 'Usage: node tools/vendor.mjs --to <folder> --namespace "MyPlugin\\Worker" [--text-domain my-plugin]' );
	console.error( 'The namespace must be a valid PHP namespace of your plugin (not "WasmWorker").' );
	process.exit( 1 );
}

if ( ! /^[a-z0-9-]+$/.test( domain ) ) {
	console.error( 'The text domain may only contain lowercase letters, digits and hyphens.' );
	process.exit( 1 );
}

const { version } = JSON.parse( await readFile( path.join( root, 'package.json' ), 'utf8' ) );

// Only a previous copy of the kit (or an empty folder) is replaced, never a folder with other files.
const existing = await readdir( target ).catch( () => [] );
if ( existing.length && ! ( await readFile( path.join( target, 'VERSION' ), 'utf8' ).catch( () => '' ) ).startsWith( 'wasm-worker-kit ' ) ) {
	console.error( `${ target } is not empty and is not a copy of the kit: choose an empty or new folder.` );
	process.exit( 1 );
}

await rm( target, { recursive: true, force: true } );
await mkdir( path.join( target, 'php' ), { recursive: true } );
await mkdir( path.join( target, 'js' ), { recursive: true } );

for ( const file of await readdir( path.join( root, 'src', 'php' ) ) ) {
	const source = await readFile( path.join( root, 'src', 'php', file ), 'utf8' );
	const scoped = source
		.replace( /^namespace WasmWorker;/m, `namespace ${ namespace };` )
		.replace( /@package WasmWorker/g, `@package ${ namespace }` )
		.replace( /, 'wasm-worker' \)/g, `, '${ domain }' )` );

	if ( scoped === source && /namespace /.test( source ) ) {
		throw new Error( `${ file }: namespace not found` );
	}
	await writeFile( path.join( target, 'php', file ), scoped );
}

for ( const file of await readdir( path.join( root, 'src', 'js' ) ) ) {
	await writeFile( path.join( target, 'js', file ), await readFile( path.join( root, 'src', 'js', file ) ) );
}

await writeFile(
	path.join( target, 'VERSION' ),
	`wasm-worker-kit ${ version }\nnamespace ${ namespace }\ntext domain ${ domain }\nGenerated by tools/vendor.mjs, do not edit: update the kit and run the tool again.\n`
);

console.log( `WASM worker kit ${ version } copied to ${ target } (namespace ${ namespace }, text domain ${ domain }).` );
